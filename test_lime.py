
import os
os.environ["KMP_DUPLICATE_LIB_OK"] = "TRUE"
os.environ["OMP_NUM_THREADS"] = "1"

import csv
import numpy as np
import torch
import torch.nn as nn
import torch.nn.functional as F
import matplotlib.pyplot as plt

from pathlib import Path
from PIL import Image
from torchvision import models, transforms
from skimage.segmentation import slic

from lime import lime_image


# ---------------------------------------------------------
# Configuration
# ---------------------------------------------------------

CHECKPOINT_PATH = "best_resnet18_oxford_pet.pth"

IMAGE_DIR = Path("./data/oxford-iiit-pet/images")
TRIMAP_DIR = Path("./data/oxford-iiit-pet/annotations/trimaps")

IMAGE_PATHS = sorted(IMAGE_DIR.glob("*.jpg"))[:30]

NUM_CLASSES = 37
IMAGE_SIZE = 224

NUM_SUPERPIXELS = 150
SLIC_COMPACTNESS = 10.0

# Number of positively weighted superpixels used in the mask.
NUM_FEATURES = 10

# Number of perturbed samples generated by LIME.
NUM_SAMPLES = 1000
BATCH_SIZE = 32

DEVICE = torch.device(
    "cuda" if torch.cuda.is_available() else "cpu"
)

MEAN = (0.485, 0.456, 0.406)
STD = (0.229, 0.224, 0.225)

GROUND_TRUTH_FOREGROUND_LABELS = (1, 3)

OUTPUT_DIR = Path("./lime_results")
OUTPUT_DIR.mkdir(exist_ok=True)


# ---------------------------------------------------------
# 1. Load ResNet18
# ---------------------------------------------------------

def load_model(checkpoint_path, num_classes, device):

    model = models.resnet18(weights=None)
    model.fc = nn.Linear(model.fc.in_features, num_classes)

    checkpoint = torch.load(
        checkpoint_path,
        map_location="cpu",
        weights_only=True,
    )

    if isinstance(checkpoint, dict):
        if "model_state_dict" in checkpoint:
            state_dict = checkpoint["model_state_dict"]
        elif "state_dict" in checkpoint:
            state_dict = checkpoint["state_dict"]
        else:
            state_dict = checkpoint
    else:
        raise TypeError("Expected a state-dict checkpoint.")

    state_dict = {
        key.removeprefix("module."): value
        for key, value in state_dict.items()
    }

    model.load_state_dict(state_dict, strict=True)
    model.to(device)
    model.eval()

    return model


model = load_model(
    CHECKPOINT_PATH,
    NUM_CLASSES,
    DEVICE,
)

print(f"Loaded model on {DEVICE}")


# ---------------------------------------------------------
# 2. Preprocessing
# ---------------------------------------------------------

preprocess = transforms.Compose([
    transforms.ToTensor(),
    transforms.Normalize(mean=MEAN, std=STD),
])


# ---------------------------------------------------------
# 3. Batch prediction function for LIME
# ---------------------------------------------------------

@torch.inference_mode()
def predict_batch(images):
    """
    Input:
        Batch of RGB numpy images, shape (N, H, W, 3).
        Pixel range [0, 1].

    Output:
        Class probabilities, shape (N, NUM_CLASSES).
    """

    tensors = []

    for image in images:

        image = np.asarray(image, dtype=np.float32)
        image = np.clip(image, 0.0, 1.0)

        pil_image = Image.fromarray(
            np.uint8(np.round(image * 255.0))
        )

        tensors.append(preprocess(pil_image))

    batch = torch.stack(tensors).to(DEVICE)

    logits = model(batch)
    probabilities = F.softmax(logits, dim=1)

    return probabilities.cpu().numpy()


# ---------------------------------------------------------
# 4. Load image and ground-truth trimap
# ---------------------------------------------------------

def load_image_and_mask(image_path):

    image_path = Path(image_path)

    image_pil = Image.open(image_path).convert("RGB")

    image_pil = image_pil.resize(
        (IMAGE_SIZE, IMAGE_SIZE),
        Image.Resampling.BILINEAR,
    )

    image = np.asarray(
        image_pil,
        dtype=np.float32,
    ) / 255.0

    trimap_path = TRIMAP_DIR / f"{image_path.stem}.png"

    if not trimap_path.exists():
        raise FileNotFoundError(
            f"Ground-truth trimap not found: {trimap_path}"
        )

    trimap = Image.open(trimap_path)

    trimap = trimap.resize(
        (IMAGE_SIZE, IMAGE_SIZE),
        Image.Resampling.NEAREST,
    )

    trimap = np.asarray(trimap)

    gt_mask = np.isin(
        trimap,
        GROUND_TRUTH_FOREGROUND_LABELS,
    )

    if gt_mask.sum() == 0:
        raise ValueError(
            f"Empty ground-truth mask: {trimap_path}"
        )

    return image, gt_mask


# ---------------------------------------------------------
# 5. SLIC segmentation function for LIME
# ---------------------------------------------------------

def lime_segmentation(image):

    return slic(
        image,
        n_segments=NUM_SUPERPIXELS,
        compactness=SLIC_COMPACTNESS,
        start_label=0,
        channel_axis=-1,
        enforce_connectivity=True,
    )


# ---------------------------------------------------------
# 6. Calculate metrics
# ---------------------------------------------------------

def calculate_metrics(predicted_mask, gt_mask):

    predicted_mask = predicted_mask.astype(bool)
    gt_mask = gt_mask.astype(bool)

    intersection = np.logical_and(
        predicted_mask,
        gt_mask,
    ).sum()

    predicted_area = predicted_mask.sum()

    # This matches the precision-style metric in your
    # adaptive segmentation script.
    precision = (
        intersection / predicted_area
        if predicted_area > 0 else 0.0
    )

    union = np.logical_or(
        predicted_mask,
        gt_mask,
    ).sum()

    iou = (
        intersection / union
        if union > 0 else 0.0
    )

    return {
        "lime_precision": float(precision),
        "lime_iou": float(iou),
        "intersection_pixels": int(intersection),
        "predicted_area": int(predicted_area),
        "ground_truth_area": int(gt_mask.sum()),
    }


# ---------------------------------------------------------
# 7. Extract positive LIME explanation mask
# ---------------------------------------------------------

def get_positive_lime_mask(
    explanation,
    target_class,
    num_features,
):
    """
    Extracts the positively weighted superpixels for
    the target class.

    Returns:
        Binary mask of positively contributing superpixels.
    """

    segments = explanation.segments

    # Local explanation: list of (superpixel_id, weight).
    local_weights = explanation.local_exp[target_class]

    # Keep only positively weighted features.
    positive_features = [
        (segment_id, weight)
        for segment_id, weight in local_weights
        if weight > 0
    ]

    # Select the strongest positive features.
    positive_features = sorted(
        positive_features,
        key=lambda item: item[1],
        reverse=True,
    )

    selected_features = positive_features[:num_features]

    selected_ids = [
        segment_id
        for segment_id, weight in selected_features
    ]

    positive_mask = np.isin(
        segments,
        selected_ids,
    )

    return positive_mask, selected_features


# ---------------------------------------------------------
# 8. Run LIME on one image
# ---------------------------------------------------------

def run_lime(image_path, image_index):

    image, gt_mask = load_image_and_mask(image_path)

    # Original prediction determines the target class.
    original_probabilities = predict_batch(
        np.expand_dims(image, axis=0)
    )[0]

    original_class = int(
        np.argmax(original_probabilities)
    )

    original_confidence = float(
        original_probabilities[original_class]
    )

    print(f"\nImage: {Path(image_path).name}")
    print("Predicted class:", original_class)
    print("Original confidence:", original_confidence)

    # Each image gets a reproducible LIME random seed.
    explainer = lime_image.LimeImageExplainer(
        random_state=1000 + image_index
    )

    # Generate explanation.
    explanation = explainer.explain_instance(
        image,
        classifier_fn=predict_batch,
        labels=(original_class,),
        top_labels=None,
        hide_color=0,
        num_features=NUM_FEATURES,
        num_samples=NUM_SAMPLES,
        batch_size=BATCH_SIZE,
        segmentation_fn=lime_segmentation,
        distance_metric="cosine",
    )

    # Extract positively supporting superpixels.
    lime_mask, selected_features = get_positive_lime_mask(
        explanation=explanation,
        target_class=original_class,
        num_features=NUM_FEATURES,
    )

    # Calculate metrics.
    metrics = calculate_metrics(
        lime_mask,
        gt_mask,
    )

    print(
        f"Positive superpixels selected: "
        f"{len(selected_features)}"
    )

    print(
        f"Positive mask area: {lime_mask.sum()} pixels"
    )

    print(
        f"Ground-truth intersection: "
        f"{metrics['intersection_pixels']}"
    )

    print(
        f"LIME precision: {metrics['lime_precision']:.4f}"
    )

    print(
        f"LIME IoU: {metrics['lime_iou']:.4f}"
    )

    return {
        "image": image,
        "gt_mask": gt_mask,
        "lime_mask": lime_mask,
        "segments": explanation.segments,
        "metrics": metrics,
        "selected_features": selected_features,
        "original_class": original_class,
        "original_confidence": original_confidence,
    }


# ---------------------------------------------------------
# 9. Evaluate test dataset
# ---------------------------------------------------------

dataset_metrics = {
    "lime_precision": [],
    "lime_iou": [],
    "intersection_pixels": [],
}

first_result = None
per_image_results = []

for image_index, image_path in enumerate(IMAGE_PATHS):

    print(
        f"\nProcessing image "
        f"{image_index + 1}/{len(IMAGE_PATHS)}"
    )

    result = run_lime(
        image_path,
        image_index,
    )

    if first_result is None:
        first_result = result

    per_image_results.append({
        "image": Path(image_path).name,
        **result["metrics"],
    })

    for key in dataset_metrics:
        dataset_metrics[key].append(
            result["metrics"][key]
        )


# ---------------------------------------------------------
# 10. Calculate dataset averages
# ---------------------------------------------------------

mean_metrics = {
    key: np.mean(values)
    for key, values in dataset_metrics.items()
}

std_metrics = {
    key: np.std(values)
    for key, values in dataset_metrics.items()
}

print("\n========================================")
print("LIME TEST DATASET RESULTS")
print("========================================")

print("Number of images:", len(IMAGE_PATHS))

for key in dataset_metrics:

    print(
        f"{key}: "
        f"{mean_metrics[key]:.4f} "
        f"(±{std_metrics[key]:.4f})"
    )


